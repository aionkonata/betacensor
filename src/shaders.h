#ifndef BC_SHADERS_H
#define BC_SHADERS_H

/*
 * The censor shaders, shared by the two things that draw boxes: the live
 * Wayland overlay (src/overlay.c) and the offline video pass (src/video.c).
 *
 * They live in a header, and not in either of those files, for one reason --
 * an effect must look the same on a recorded file as it does on screen. A
 * second copy of this source would drift, and it would drift silently: an
 * effect fixed in one place and left alone in the other still compiles, still
 * runs, and still covers, so nothing would flag it.
 */

static const char *BC_VS_SRC =
"#version 430 core\n"
"void main() {\n"
"    vec2 p = vec2((gl_VertexID << 1) & 2, gl_VertexID & 2);\n"
"    gl_Position = vec4(p * 2.0 - 1.0, 0.0, 1.0);\n"
"}\n";

static const char *BC_FS_SRC =
"#version 430 core\n"
"layout(binding = 0) uniform sampler2D uSrc;\n"
"uniform vec2  uSize;\n"
"uniform float uBlock;\n"
"uniform float uAlpha;\n"
"uniform int   uEffect;\n"
"uniform float uTime;\n"
"uniform vec4  uBox;      /* xy = bottom-left, zw = size, GL coords */\n"
"uniform float uFeather;  /* px of soft edge, *outside* uBox */\n"
"uniform float uAngle;    /* radians; the box is rotated about its centre */\n"
"uniform vec3  uColor;    /* solid fill colour, un-premultiplied */\n"
"uniform int   uAutoCol;  /* 1 = sample the fill colour from around the box */\n"
"uniform float uOutline;  /* px of outline, outward from uBox; 0 = none */\n"
"uniform vec3  uOutCol;\n"
"uniform float uShadow;   /* px of shadow falloff beyond the outline */\n"
"uniform float uShadowA;  /* peak shadow alpha */\n"
"layout(binding = 2) uniform sampler2D uMask;\n"
"uniform int   uUseMask;  /* 1 = clip this box to the subject silhouette */\n"
"/* Screen 0..1 -> mask uv. The silhouette is produced in the segmentation\n"
"   model's letterboxed input space, so this carries that letterbox: xy is\n"
"   the uv of the screen's top-left corner, zw of its bottom-right. */\n"
"uniform vec4  uMaskRect;\n"
"layout(binding = 1) uniform sampler2D uFont;\n"
"uniform int   uText[64];  /* caption, one code point per element */\n"
"uniform int   uTextLen;\n"
"uniform int   uTextMode; /* 0 = the effect's own colour, 1 = uTextCol, 2 = wave */\n"
"uniform vec3  uTextCol;  /* glyph colour when uTextMode is 1 */\n"
"out vec4 frag;\n"
"\n"
"/* texture row 0 is the top of the screen; gl_FragCoord is bottom-left\n"
"   origin, so flip v. */\n"
"vec3 src(vec2 p) {\n"
"    return texture(uSrc, vec2(p.x / uSize.x, 1.0 - p.y / uSize.y)).rgb;\n"
"}\n"
"\n"
"/* Integer bit-mixing hash. The usual fract(sin(dot(...))) trick correlates\n"
"   badly across a grid -- neighbouring cells land on nearby sine phases, which\n"
"   showed up as a visible checkerboard rather than as static. */\n"
"uint hash_u(uint x) {\n"
"    x ^= x >> 16; x *= 0x7feb352du;\n"
"    x ^= x >> 15; x *= 0x846ca68bu;\n"
"    x ^= x >> 16; return x;\n"
"}\n"
"\n"
"float rnd(ivec2 c, int f) {\n"
"    uint h = hash_u(uint(c.x) * 73856093u ^\n"
"                    uint(c.y) * 19349663u ^\n"
"                    uint(f)   * 83492791u);\n"
"    return float(h) * (1.0 / 4294967296.0);\n"
"}\n"
"\n"
"/* The two obscuring primitives. The decorative effects that sample the\n"
"   screen (glitch, RGB shift) are built on blur_at rather than on the raw\n"
"   pixels, so they cover rather than merely decorate. */\n"
"vec3 blur_at(vec2 p) {\n"
"    vec3 acc = vec3(0.0);\n"
"    float st = uBlock * 2.0 / 6.0;\n"
"    for (int j = 0; j < 7; j++)\n"
"        for (int i = 0; i < 7; i++)\n"
"            acc += src(p + (vec2(i, j) - 3.0) * st);\n"
"    return acc / 49.0;\n"
"}\n"
"\n"
"/* Cheaper kernel for effects that need several blurs per fragment. RGB\n"
"   shift runs three, and at 7x7 that cost 147 taps and pulled presentation\n"
"   from 180 fps to 157 -- below the output's refresh. At 5x5 the three\n"
"   passes total 75 taps, and the difference is invisible under a channel\n"
"   split. */\n"
"vec3 blur_lite(vec2 p) {\n"
"    vec3 acc = vec3(0.0);\n"
"    float st = uBlock * 2.0 / 4.0;\n"
"    for (int j = 0; j < 5; j++)\n"
"        for (int i = 0; i < 5; i++)\n"
"            acc += src(p + (vec2(i, j) - 2.0) * st);\n"
"    return acc / 25.0;\n"
"}\n"
"\n"
"vec3 pixelate_at(vec2 p) {\n"
"    vec2 blk = floor(p / uBlock) * uBlock;\n"
"    vec3 acc = vec3(0.0);\n"
"    for (int j = 0; j < 3; j++)\n"
"        for (int i = 0; i < 3; i++)\n"
"            acc += src(blk + (vec2(i, j) + 0.5) * (uBlock / 3.0));\n"
"    return acc / 9.0;\n"
"}\n"
"\n"
"/* Distance to the edge of a unit hexagon, 1.0 at the edge. The lattice\n"
"   below works in doubled coordinates, so gv arrives already scaled. */\n"
"float hex_dist(vec2 p) {\n"
"    p = abs(p);\n"
"    return max(dot(p, normalize(vec2(1.0, 1.7320508))), p.x);\n"
"}\n"
"\n"
"/* Coverage of one glyph. uv runs 0..1 across the character cell, y up;\n"
"   the atlas is one row of 95 glyphs starting at space, stored top-down,\n"
"   hence the v flip. Anything outside the cell or outside the printable\n"
"   range is blank rather than an adjacent glyph. */\n"
"float glyph(int code, vec2 uv) {\n"
"    if (code < 32 || code > 126) return 0.0;\n"
"    if (uv.x < 0.0 || uv.x >= 1.0 || uv.y < 0.0 || uv.y >= 1.0) return 0.0;\n"
"    float gx = (float(code - 32) + uv.x) * (1.0 / 95.0);\n"
"    return texture(uFont, vec2(gx, 1.0 - uv.y)).r;\n"
"}\n"
"\n"
"/* Colour for the glyphs of the caption and wall effects. `dflt` is what the\n"
"   effect would have used on its own, so mode 0 -- which is what a box built\n"
"   without an opinion carries -- changes nothing.\n"
"   Mode 2 sweeps the hue along a diagonal and in time. `p` is the position it\n"
"   is sampled at: the wall passes its *scrolled* coordinate, so the colour\n"
"   travels with the text rather than the text sliding underneath a stationary\n"
"   rainbow.\n"
"   This only ever picks the ink. The opaque base is drawn first and is what\n"
"   covers, so no colour here -- including one that matches the base -- can\n"
"   uncover anything. */\n"
"/* Halo around a glyph: the same glyph re-read on two rings and kept at its\n"
"   strongest, which bleeds its ink outward. The offsets are in cell-relative\n"
"   units and a cell is twice as tall as it is wide, so x is doubled to keep\n"
"   the halo round on screen rather than squashed.\n"
"   glyph() returns 0 outside its own cell, so the halo clips at the cell\n"
"   edge instead of bleeding into a neighbour's letter -- which is what makes\n"
"   this safe to do without knowing the neighbouring code point. */\n"
"float glyph_glow(int code, vec2 uv, float r) {\n"
"    float outer = 0.0, inner = 0.0;\n"
"    for (int i = 0; i < 8; i++) {\n"
"        float a = float(i) * 0.7853982;\n"
"        vec2  d = vec2(cos(a) * 2.0, sin(a));\n"
"        outer = max(outer, glyph(code, uv + d * r));\n"
"        inner = max(inner, glyph(code, uv + d * r * 0.5));\n"
"    }\n"
"    return max(inner, outer * 0.45);\n"
"}\n"
"\n"
"/* The colour of what surrounds the box, for an automatic censor colour.\n"
"   Twelve taps on a ring just outside the box rather than a true average of\n"
"   the border: an average needs every edge pixel, which is a reduction, and a\n"
"   reduction per fragment is far more work than the twelve fetches that give\n"
"   the same answer to within a shade. Every tap is clamped into the frame, so\n"
"   a box against the screen edge samples the edge rather than wrapping.\n"
"   The result is only ever a colour to fill an opaque bar with: it is picked\n"
"   for looks and cannot change how much is covered. */\n"
"vec3 ring_color() {\n"
"    vec2 c = uBox.xy + uBox.zw * 0.5;\n"
"    vec2 r = uBox.zw * 0.5 + vec2(6.0);\n"
"    vec3 sum = vec3(0.0);\n"
"    for (int i = 0; i < 12; i++) {\n"
"        float a = float(i) * 0.5235988;\n"
"        vec2  p = clamp(c + vec2(cos(a), sin(a)) * r, vec2(0.5), uSize - 0.5);\n"
"        sum += texture(uSrc, p / uSize).rgb;\n"
"    }\n"
"    return sum / 12.0;\n"
"}\n"
"\n"
"vec3 text_col(vec3 dflt, vec2 p) {\n"
"    if (uTextMode == 1)\n"
"        return uTextCol;\n"
"    if (uTextMode == 2) {\n"
"        float h = fract((p.x + p.y) * 0.0012 - uTime * 0.14);\n"
"        return clamp(abs(fract(h + vec3(0.0, 0.66667, 0.33333)) * 6.0 - 3.0)\n"
"                     - 1.0, 0.0, 1.0);\n"
"    }\n"
"    return dflt;\n"
"}\n"
"\n"
"void main() {\n"
"    vec2 lp = (gl_FragCoord.xy - uBox.xy) / max(uBox.zw, vec2(1.0));\n"
"    vec3 col;\n"
"\n"
"    if (uEffect == 2) {\n"
"        /* Blur. Radius reuses the pixelate block figure so 'strength'\n"
"           means the same thing to the user in both. Grid-sampled rather\n"
"           than a true gaussian -- cheaper, and indistinguishable once the\n"
"           radius is wide enough to be doing its job. */\n"
"        col = blur_at(gl_FragCoord.xy);\n"
"    } else if (uEffect == 3) {\n"
"        /* Static. Samples nothing, so it cannot leak the content it is\n"
"           covering even if the capture is stale -- the one effect that is\n"
"           safe by construction rather than by radius. Grain is near\n"
"           pixel-sized and only loosely tied to strength: static reads as\n"
"           static because it is fine and uncorrelated. */\n"
"        float grain = clamp(floor(uBlock / 24.0), 1.0, 4.0);\n"
"        ivec2 cell = ivec2(floor(gl_FragCoord.xy / grain));\n"
"        /* Resampled at 60 Hz rather than per presented frame, so it does\n"
"           not shimmer differently on a 180 Hz output. */\n"
"        col = vec3(rnd(cell, int(uTime * 60.0)));\n"
"    } else if (uEffect == 4) {\n"
"        /* Glitch: horizontal strips of the *blurred* screen, slid\n"
"           sideways by a per-strip random amount. Built on blur so a strip\n"
"           that happens to slide by zero is still covered -- and so it\n"
"           inherits blur's caveat, that it is only as safe as its radius. */\n"
"        float rowh = max(uBlock, 8.0);\n"
"        int   row  = int(floor(gl_FragCoord.y / rowh));\n"
"        int   t    = int(uTime * 12.0);\n"
"        float off  = (rnd(ivec2(row, 0), t) - 0.5) * uBox.z * 0.6;\n"
"        vec2  p    = vec2(gl_FragCoord.x + off, gl_FragCoord.y);\n"
"        col = blur_at(p);\n"
"        /* a few strips tear harder and split colour */\n"
"        if (rnd(ivec2(row, 1), t) > 0.85) {\n"
"            col.r = blur_at(p + vec2(rowh, 0.0)).r;\n"
"            col.b = blur_at(p - vec2(rowh, 0.0)).b;\n"
"        }\n"
"    } else if (uEffect == 5) {\n"
"        /* RGB shift. On its own a channel offset does not obscure\n"
"           anything -- the content stays readable, just fringed -- so it\n"
"           is applied to a blurred base, never to the raw screen. */\n"
"        float d = max(uBlock * 0.35, 3.0);\n"
"        vec2  p = gl_FragCoord.xy;\n"
"        col = vec3(blur_lite(p + vec2(d, 0.0)).r,\n"
"                   blur_lite(p).g,\n"
"                   blur_lite(p - vec2(d, 0.0)).b);\n"
"    } else if (uEffect == 6) {\n"
"        /* Privacy tape: hazard stripes. The bar is drawn spanning the\n"
"           whole screen rather than fitted to the box (see the draw path),\n"
"           so the stripes run continuously across the display and the\n"
"           detection is covered by something strictly larger than it.\n"
"           Opaque by construction -- samples nothing. */\n"
"        float w  = max(uBlock, 16.0);\n"
"        float st = fract((gl_FragCoord.x + gl_FragCoord.y) / w\n"
"                         - uTime * 0.35);\n"
"        col = st < 0.5 ? vec3(0.96, 0.78, 0.05) : vec3(0.07, 0.07, 0.07);\n"
"    } else if (uEffect == 7) {\n"
"        /* Halftone. Built on the pixelated base, not the raw screen: the\n"
"           dots only encode local brightness, but the brightness they read\n"
"           has to be an average already or fine detail modulates dot size\n"
"           and the content comes back as texture. */\n"
"        vec3  base = pixelate_at(gl_FragCoord.xy);\n"
"        float lum  = dot(base, vec3(0.299, 0.587, 0.114));\n"
"        float cell = max(uBlock * 0.75, 3.0);\n"
"        /* Screen angle. Print uses 45 degrees because a grid aligned to the\n"
"           axes reads as a grid; rotated, it reads as tone. */\n"
"        const float ca = 0.70710678, sa = 0.70710678;\n"
"        vec2 rp = vec2(gl_FragCoord.x * ca - gl_FragCoord.y * sa,\n"
"                       gl_FragCoord.x * sa + gl_FragCoord.y * ca);\n"
"        vec2 c  = mod(rp, cell) - cell * 0.5;\n"
"        /* Dot radius from ink coverage: dark areas print big dots. Capped\n"
"           below the cell half-diagonal so the darkest tone is solid. */\n"
"        float r  = (1.0 - lum) * cell * 0.72;\n"
"        float ink = 1.0 - smoothstep(-1.0, 1.0, length(c) - r);\n"
"        col = mix(vec3(0.93), vec3(0.05), ink);\n"
"    } else if (uEffect == 8) {\n"
"        /* Sobel edges of the *pixelated* image, drawn on near-black.\n"
"           Edges of a block-averaged image are block boundaries, so this\n"
"           outlines shapes without reproducing what is inside them, and the\n"
"           background is opaque rather than transparent. A gradient of the\n"
"           raw screen would trace the content itself. */\n"
"        float st = max(uBlock, 2.0);\n"
"        vec3 l = pixelate_at(gl_FragCoord.xy + vec2(-st, 0.0));\n"
"        vec3 r = pixelate_at(gl_FragCoord.xy + vec2( st, 0.0));\n"
"        vec3 d = pixelate_at(gl_FragCoord.xy + vec2(0.0, -st));\n"
"        vec3 u = pixelate_at(gl_FragCoord.xy + vec2(0.0,  st));\n"
"        const vec3 W = vec3(0.299, 0.587, 0.114);\n"
"        float gx = dot(r, W) - dot(l, W);\n"
"        float gy = dot(u, W) - dot(d, W);\n"
"        float e  = clamp(length(vec2(gx, gy)) * 5.0, 0.0, 1.0);\n"
"        col = mix(vec3(0.02), vec3(0.10, 0.95, 0.45), e);\n"
"    } else if (uEffect == 9) {\n"
"        /* Triangular mosaic: each square cell is split on its diagonal and\n"
"           both halves are flooded with the average around their centroid.\n"
"           Same obscuring argument as pixelate -- the output is piecewise\n"
"           constant -- but the diagonals break up the axis-aligned grid. */\n"
"        float cell = max(uBlock, 3.0);\n"
"        vec2  g    = gl_FragCoord.xy / cell;\n"
"        vec2  f    = fract(g);\n"
"        vec2  orig = floor(g) * cell;\n"
"        vec2  cen  = (f.x + f.y > 1.0)\n"
"                     ? orig + cell * vec2(2.0 / 3.0, 2.0 / 3.0)\n"
"                     : orig + cell * vec2(1.0 / 3.0, 1.0 / 3.0);\n"
"        vec3 acc = vec3(0.0);\n"
"        for (int j = 0; j < 2; j++)\n"
"            for (int i = 0; i < 2; i++)\n"
"                acc += src(cen + (vec2(i, j) - 0.5) * cell * 0.4);\n"
"        col = acc * 0.25;\n"
"    } else if (uEffect == 10) {\n"
"        /* Cluster: a mass of overlapping discs. Like static and tape it\n"
"           samples nothing, so it covers by construction rather than by\n"
"           radius. The opaque base is written first and the discs only\n"
"           decorate it -- which is the whole reason a gap between discs\n"
"           is not a hole. Neighbouring cells are visited so a disc that\n"
"           spills past its own cell is not clipped at the boundary. */\n"
"        float cell = max(uBlock * 0.9, 6.0);\n"
"        ivec2 c0   = ivec2(floor(gl_FragCoord.xy / cell));\n"
"        col = vec3(0.05, 0.05, 0.07);\n"
"        for (int j = -1; j <= 1; j++) {\n"
"            for (int i = -1; i <= 1; i++) {\n"
"                ivec2 c   = c0 + ivec2(i, j);\n"
"                vec2  jit = vec2(rnd(c, 0), rnd(c, 1)) - 0.5;\n"
"                vec2  ctr = (vec2(c) + 0.5 + jit * 0.7) * cell;\n"
"                float r   = (0.45 + rnd(c, 2) * 0.35) * cell;\n"
"                float a   = 1.0 - smoothstep(-1.5, 1.5,\n"
"                                length(gl_FragCoord.xy - ctr) - r);\n"
"                float sh  = 0.25 + rnd(c, 3) * 0.55;\n"
"                col = mix(col, vec3(sh) * vec3(0.85, 0.88, 1.0), a);\n"
"            }\n"
"        }\n"
"    } else if (uEffect == 11) {\n"
"        /* Splatter: ink blobs combined with a smooth minimum, so blobs\n"
"           that land near each other fuse into a run instead of reading\n"
"           as a row of separate discs. Ellipses at random angles rather\n"
"           than circles -- a splat is not round. Samples nothing. */\n"
"        float cell = max(uBlock * 1.6, 12.0);\n"
"        ivec2 c0   = ivec2(floor(gl_FragCoord.xy / cell));\n"
"        float k    = cell * 0.35;   /* fusion range of the smooth min */\n"
"        float d    = 1e9;\n"
"        for (int j = -1; j <= 1; j++) {\n"
"            for (int i = -1; i <= 1; i++) {\n"
"                ivec2 c   = c0 + ivec2(i, j);\n"
"                vec2  jit = vec2(rnd(c, 4), rnd(c, 5)) - 0.5;\n"
"                vec2  ctr = (vec2(c) + 0.5 + jit * 0.9) * cell;\n"
"                vec2  q   = gl_FragCoord.xy - ctr;\n"
"                float th  = rnd(c, 6) * 6.2831853;\n"
"                vec2  e   = vec2(q.x * cos(th) - q.y * sin(th),\n"
"                                 q.x * sin(th) + q.y * cos(th));\n"
"                e /= vec2(1.0, 0.6 + rnd(c, 7) * 0.7);\n"
"                float di  = length(e) - (0.34 + rnd(c, 8) * 0.30) * cell;\n"
"                float h   = clamp(0.5 + 0.5 * (d - di) / k, 0.0, 1.0);\n"
"                d = mix(d, di, h) - k * h * (1.0 - h);\n"
"            }\n"
"        }\n"
"        float ink = 1.0 - smoothstep(-1.5, 1.5, d);\n"
"        col = mix(vec3(0.93, 0.92, 0.90), vec3(0.05, 0.05, 0.06), ink);\n"
"    } else if (uEffect == 12) {\n"
"        /* Shape: a hexagonal tiling, each tile flooded with the average\n"
"           of the screen around its own centre -- pixelate on a hex\n"
"           lattice. The obscuring argument is pixelate's: the output is\n"
"           piecewise constant per tile, so nothing inside a tile survives.\n"
"           Hexagons tile the plane completely -- there is no interstitial\n"
"           space to leak through, which is why the grout is drawn *inside*\n"
"           a tile and not between tiles. */\n"
"        float cell = max(uBlock * 1.2, 8.0);\n"
"        vec2  p    = gl_FragCoord.xy / cell;\n"
"        /* Two offset rectangular lattices; the nearer centre wins. The\n"
"           doubled coordinates put the hexagon edge at 1.0. */\n"
"        vec2  s    = vec2(1.0, 1.7320508);\n"
"        vec2  a    = mod(p, s) * 2.0 - s;\n"
"        vec2  b    = mod(p + s * 0.5, s) * 2.0 - s;\n"
"        vec2  gv   = dot(a, a) < dot(b, b) ? a : b;\n"
"        vec2  id   = p - gv * 0.5;\n"
"        /* Tile centre back in screen pixels. Sampling around the centre\n"
"           rather than around the fragment is what makes the tile one\n"
"           flat colour: every fragment of a tile reads the same taps. */\n"
"        vec2  cen  = id * cell;\n"
"        vec3  acc  = vec3(0.0);\n"
"        for (int j = 0; j < 3; j++)\n"
"            for (int i = 0; i < 3; i++)\n"
"                acc += src(cen + (vec2(i, j) - 1.0) * cell * 0.42);\n"
"        col = acc / 9.0;\n"
"        /* Grout: the tile's own colour, darkened, so the honeycomb reads\n"
"           as edges without dropping a black grid over the picture. */\n"
"        col = mix(col, col * 0.45, smoothstep(0.88, 1.0, hex_dist(gv)));\n"
"    } else if (uEffect == 13) {\n"
"        /* Caption: an opaque bar with a word laid across it. The bar is\n"
"           drawn first and the glyphs only mark it, so a box too small to\n"
"           fit legible text is still a solid bar -- the text is decoration\n"
"           on top of the covering, never the covering itself. Samples\n"
"           nothing. */\n"
"        /* The box's own frame, so the word runs *along* a rotated bar\n"
"           instead of staying level while the bar turns under it. Raw\n"
"           gl_FragCoord here measured from the unrotated origin, which on\n"
"           a turned bar both mis-placed the text and left it upright.\n"
"           Wall-of-text deliberately does not do this: its grid is in\n"
"           screen space so the glyphs do not crawl as the box moves. */\n"
"        vec2  bhs = uBox.zw * 0.5;\n"
"        vec2  brl = gl_FragCoord.xy - (uBox.xy + bhs);\n"
"        float bcs = cos(-uAngle), bsn = sin(-uAngle);\n"
"        vec2  px  = vec2(brl.x * bcs - brl.y * bsn,\n"
"                         brl.x * bsn + brl.y * bcs) + bhs;\n"
"        col = vec3(0.04, 0.04, 0.05);\n"
"        int n = clamp(uTextLen, 0, 64);\n"
"        if (n > 0) {\n"
"            /* Fit the string to the box: bounded by the width it needs at\n"
"               a given cell height, and by the height itself. The glyphs\n"
"               are 8x16, so a cell is half as wide as it is tall. */\n"
"            float ch = min(uBox.z * 0.90 / (float(n) * 0.5), uBox.w * 0.55);\n"
"            float cw = ch * 0.5;\n"
"            vec2  o  = vec2((uBox.z - float(n) * cw) * 0.5,\n"
"                            (uBox.w - ch) * 0.5);\n"
"            float fx = (px.x - o.x) / cw;\n"
"            int   i  = int(floor(fx));\n"
"            if (i >= 0 && i < n) {\n"
"                vec2  guv = vec2(fract(fx), (px.y - o.y) / ch);\n"
"                float ink = glyph(uText[i], guv);\n"
"                vec3  tc  = text_col(vec3(0.95, 0.95, 0.93),\n"
"                                     gl_FragCoord.xy);\n"
"                col = mix(col, tc, ink);\n"
"                /* Glow, on the wave only. Added rather than mixed, and\n"
"                   only where there is no glyph, so it lights the bar up\n"
"                   around the letters without washing them out. */\n"
"                if (uTextMode == 2)\n"
"                    col += tc * glyph_glow(uText[i], guv, 0.16)\n"
"                              * 0.6 * (1.0 - ink);\n"
"            }\n"
"        }\n"
"    } else if (uEffect == 14) {\n"
"        /* Wall of text: the box filled with characters drawn from the\n"
"           hash. Same argument as caption -- opaque base first, glyphs on\n"
"           top -- so the density of the text has no bearing on whether the\n"
"           area is covered. Samples nothing.\n"
"           The grid is in screen space, not box space, so the characters\n"
"           do not crawl with the box as it moves.\n"
"           It scrolls. The offset is applied to the screen position\n"
"           *before* the cell is derived, which slides the whole sheet as\n"
"           one piece: a glyph keeps its cell and travels with it, rather\n"
"           than cells standing still and swapping their contents, which\n"
"           reads as flicker instead of as motion. Diagonally, because a\n"
"           purely vertical drift on a box that is itself moving vertically\n"
"           cancels out and the wall looks frozen.\n"
"           Speed is in cells per second rather than pixels, so raising\n"
"           the strength scales the glyphs and their motion together and\n"
"           the text takes the same time to cross either way. */\n"
"        float ch = max(uBlock, 8.0);\n"
"        float cw = ch * 0.5;\n"
"        vec2  sp = gl_FragCoord.xy + vec2(uTime * cw * 0.9,\n"
"                                          uTime * ch * -2.2);\n"
"        ivec2 c  = ivec2(floor(sp.x / cw), floor(sp.y / ch));\n"
"        int   code;\n"
"        int   n = clamp(uTextLen, 0, 64);\n"
"        if (n > 0) {\n"
"            /* Repeat the caption across the box. Each row is shifted by a\n"
"               few characters so the same letter does not line up into\n"
"               vertical stripes, which is what a plain wrap looks like. */\n"
"            int i = c.x - c.y * 3;\n"
"            code = uText[((i % n) + n) % n];\n"
"        } else {\n"
"            /* No caption set: draw from the hash. Each cell re-rolls on\n"
"               its own schedule, so the wall churns a character at a time\n"
"               rather than replacing itself wholesale. */\n"
"            int   f = int(uTime * 3.0 + rnd(c, 20) * 10.0);\n"
"            float r = rnd(c, f);\n"
"            if (r > 0.86)       code = 32;                        /* spaces,\n"
"                                                    so it reads as words */\n"
"            else if (r > 0.43)  code = 65 + int((r - 0.43) * 60.0); /* A-Z */\n"
"            else                code = 97 + int(r * 60.0);          /* a-z */\n"
"        }\n"
"        vec2 uv = vec2(fract(sp.x / cw), fract(sp.y / ch));\n"
"        float ink = glyph(code, uv);\n"
"        vec3  tc  = text_col(vec3(0.55, 0.95, 0.60), sp);\n"
"        col = mix(vec3(0.03, 0.04, 0.03), tc, ink);\n"
"        if (uTextMode == 2)\n"
"            col += tc * glyph_glow(code, uv, 0.16) * 0.6 * (1.0 - ink);\n"
"    } else if (uEffect == 0) {\n"
"        /* Solid fill. Normally done with glClear, which is cheaper -- but\n"
"           glClear cannot express a rotated rect, an outline or a shadow, so\n"
"           those come through here instead. */\n"
"        col = (uAutoCol == 1) ? ring_color() : uColor;\n"
"    } else {\n"
"        col = pixelate_at(gl_FragCoord.xy);\n"
"    }\n"
"\n"
"    /* Soft edge. The ramp lies entirely *outside* uBox: everything the\n"
"       detector actually flagged stays fully opaque, and only the added\n"
"       margin fades. Feathering inward would mean the edge of a detection\n"
"       is covered by a semi-transparent bar, which is exposed content --\n"
"       the same reason there is no fade-in. */\n"
"    /* Everything below works in the box's own frame, so a rotated box is\n"
"       the same code as an upright one -- at uAngle 0 the rotation is the\n"
"       identity and this reduces exactly to the old axis-aligned test. The\n"
"       scissor is only ever the *bounding* box of a rotated rect, so the\n"
"       corners it leaves over have to be rejected here. */\n"
"    /* Clip to the subject silhouette, when one was supplied and this box\n"
"       asked for it. Only ever *removes* covered area, so it is the one\n"
"       thing here that can expose content the detector flagged -- which is\n"
"       why it is opt-in, why the mask is dilated before it gets here, and\n"
"       why an absent mask means cover everything rather than nothing.\n"
"       Tested before the effect's own alpha so a clipped fragment costs\n"
"       nothing further. */\n"
"    /* The mask carries three levels, not two: covered, outline, and gone.\n"
"       The outline band is rasterised into it on the CPU, as the shape grown\n"
"       outward minus the shape -- so an outline round a traced shape follows\n"
"       that shape. Drawing it from uBox instead, the way an unmasked box\n"
"       does, put a rectangle round the *bounding box* and then let the clip\n"
"       below chop it up, which is how it came to look cut off. One extra\n"
"       level in a texture already being read costs nothing; walking a ring\n"
"       of taps per fragment to find the boundary here would have. */\n"
"    bool maskEdge = false;\n"
"    if (uUseMask == 1) {\n"
"        vec2 t  = gl_FragCoord.xy / uSize;\n"
"        vec2 uv = mix(uMaskRect.xy, uMaskRect.zw, t);\n"
"        if (uv.x < 0.0 || uv.x > 1.0 || uv.y < 0.0 || uv.y > 1.0)\n"
"            discard;   /* outside the letterbox: the model never saw it */\n"
"        float m = texture(uMask, uv).r;\n"
"        if (m < 0.25)\n"
"            discard;\n"
"        maskEdge = m < 0.75;\n"
"    }\n"
"    if (maskEdge) {\n"
"        /* Opaque, like the box outline it stands in for: it adds covered\n"
"           area and so can only help. */\n"
"        frag = vec4(uOutCol * uAlpha, uAlpha);\n"
"        return;\n"
"    }\n"
"\n"
"    vec2  hs   = uBox.zw * 0.5;\n"
"    vec2  rel  = gl_FragCoord.xy - (uBox.xy + hs);\n"
"    float cs = cos(-uAngle), sn = sin(-uAngle);\n"
"    vec2  loc  = vec2(rel.x * cs - rel.y * sn, rel.x * sn + rel.y * cs);\n"
"    float outside = length(max(abs(loc) - hs, vec2(0.0)));\n"
"    /* A masked shape has already had its outline drawn, from the mask. The\n"
"       bands below are measured from uBox, which for a traced shape is only\n"
"       its bounding box -- so letting them run would draw a second outline\n"
"       round the rectangle the shape happens to sit in. */\n"
"    if (uUseMask == 1) outside = 0.0;\n"
"\n"
"    /* Outline, then shadow, then the soft edge -- three disjoint bands\n"
"       measured by how far outside uBox the fragment is. Each begins where\n"
"       the last ends, so the box interior is never touched by any of them\n"
"       and the effect keeps the whole of the area it was given. */\n"
"    float a = uAlpha;\n"
"    float edge = outside - uOutline;   /* distance past the outline */\n"
"\n"
"    if (uOutline > 0.0 && outside > 0.0 && edge <= 0.0) {\n"
"        col = uOutCol;                 /* opaque: it adds covered area */\n"
"    } else if (edge > 0.0) {\n"
"        if (uShadow > 0.0 && edge <= uShadow) {\n"
"            /* Sits beyond the outline, over screen that was never\n"
"               censored, so its transparency costs no coverage. */\n"
"            col = vec3(0.0);\n"
"            a  *= uShadowA * (1.0 - smoothstep(0.0, uShadow, edge));\n"
"        } else if (uFeather > 0.0) {\n"
"            a *= 1.0 - smoothstep(0.0, uFeather, edge);\n"
"        } else {\n"
"            discard;\n"
"        }\n"
"        if (a <= 0.0)\n"
"            discard;\n"
"    }\n"
"    /* premultiplied: Wayland requires it, and it is what the\n"
"       blend below expects. */\n"
"    frag = vec4(col * a, a);\n"
"}\n";

#endif /* BC_SHADERS_H */
